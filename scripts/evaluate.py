"""Evaluate ResNet on pre-computed DroneRFa features.

Usage:
  python scripts/evaluate.py --feature stft --data-dir ~/Desktop/dataset/DroneRFa_stft_awgn_random_16class_h5 --model-path outputs/models/best_stft_16class_model.pth --split-manifest outputs/splits/full_16class_seed42.csv
  python scripts/evaluate.py --feature cpp --data-dir ~/Desktop/dataset/DroneRFa_cpp_awgn_random_16class_h5 --model-path outputs/models/best_cpp_16class_model.pth --split-manifest outputs/splits/full_16class_seed42.csv

"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

import numpy as np
import torch
import torch.nn as nn
from sklearn.metrics import confusion_matrix
from torch.utils.data import DataLoader

from src.data.class_filter import RemappedSubset, add_exclusion_suffix, build_class_mapping
from src.data.drone_rfa_io import NUM_ORIGINAL_CLASSES
from src.data.splits import load_test_subset
from src.models.resnet import DroneRFaResNet18
from src.training.evaluator import evaluate_with_predictions
from src.training.metrics import compute_metrics, save_confusion_matrix_image
from src.training.model_io import load_model
from src.utils.cli import log_current_command
from src.utils.device import default_device
from src.utils.feature_config import get_feature_config
from src.utils.logger import logger
from src.utils.paths import figures_dir, metrics_dir

BATCH_SIZE = 64


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Evaluate ResNet on pre-computed DroneRFa features", allow_abbrev=False)
    parser.add_argument("--feature", type=str, default="stft", choices=("stft", "cpp"))
    parser.add_argument("--data-dir", type=str, default=None, help="Directory containing feature .h5 files")
    parser.add_argument("--model-path", type=str, default=None, help="Path to model weights")
    parser.add_argument("--batch-size", type=int, default=BATCH_SIZE)
    parser.add_argument("--num-workers", type=int, default=0,
                        help="DataLoader workers (0 = main process only)")
    parser.add_argument("--device", type=str, default=default_device(),
                        help="Device, e.g. 'cuda:0', 'cuda:1', 'mps', 'cpu'")
    parser.add_argument("--cm-image-path", type=str, default=None, help="Path to save confusion matrix image")
    parser.add_argument("--split-manifest", type=str, required=True,
                        help="Existing CSV manifest generated by scripts/train.py")
    parser.add_argument("--exclude-labels", type=int, nargs="*", default=None,
                        help="Original class labels excluded during training")
    args = parser.parse_args(argv)

    # 按特征补齐默认路径；额外排除类别时保留独立的模型和图片命名。
    config = get_feature_config(args.feature)
    args.data_dir = os.path.expanduser(args.data_dir) if args.data_dir is not None else config.default_data_dir
    args.model_path = (
        os.path.expanduser(args.model_path)
        if args.model_path is not None
        else add_exclusion_suffix(config.model_name, args.exclude_labels)
    )
    args.cm_image_path = (
        os.path.expanduser(args.cm_image_path)
        if args.cm_image_path is not None
        else add_exclusion_suffix(figures_dir() / config.cm_image_name, args.exclude_labels)
    )
    args.split_manifest = os.path.expanduser(args.split_manifest)
    return args


def main() -> None:
    # 校验运行参数，并确认评估使用的划分清单已存在。
    args = parse_args()
    log_current_command(logger)
    if args.batch_size <= 0 or args.num_workers < 0:
        raise ValueError("batch-size must be positive and num-workers must be non-negative")
    config = get_feature_config(args.feature)
    if not Path(args.split_manifest).is_file():
        raise FileNotFoundError(f"Split manifest does not exist: {args.split_manifest}")

    # 初始化计算设备，CUDA 模式下设置当前设备。
    device = torch.device(args.device)
    if device.type == "cuda":
        torch.cuda.set_device(device)

    logger.info("Using device: %s", device)
    if device.type == "cuda":
        logger.info("GPU: %s", torch.cuda.get_device_name(0))

    dataset = config.dataset_class(args.data_dir)
    try:
        logger.info("Loaded %d %s samples from %d .h5 files in %s",
                    len(dataset), config.name, len(set(s[0] for s in dataset.index)), args.data_dir)

        # 严格复用训练生成的文件级划分，避免重新划分引入数据泄漏。
        test_ds = load_test_subset(
            dataset,
            manifest_path=args.split_manifest,
        )

        # 过滤排除类别，并映射为与模型输出一致的连续标签。
        mapping = build_class_mapping(NUM_ORIGINAL_CLASSES, args.exclude_labels)
        test_ds = RemappedSubset(test_ds, mapping)
        logger.info("Class mapping (model -> original): %s", mapping.original_labels)
        test_file_count = len({dataset.index[index][0] for index in test_ds.indices})
        logger.info(
            "Loaded test split from %s: %d files, %d samples",
            args.split_manifest,
            test_file_count,
            len(test_ds),
        )

        # 评估按样本顺序读取；多进程模式才启用预取和常驻工作进程。
        loader_kwargs = {
            "batch_size": args.batch_size,
            "num_workers": args.num_workers,
            "pin_memory": device.type == "cuda",
        }
        if args.num_workers > 0:
            loader_kwargs["prefetch_factor"] = 4
            loader_kwargs["persistent_workers"] = True

        test_loader = DataLoader(test_ds, shuffle=False, **loader_kwargs)

        # 按保留类别数构建模型；纯权重文件名由 load_model 解析到默认模型目录。
        model = DroneRFaResNet18(num_classes=mapping.num_classes).to(device)
        logger.info("Loading model from %s", args.model_path)
        state_dict = load_model(args.model_path, map_location=device)
        model.load_state_dict(state_dict)

        # 关闭梯度的评估循环由辅助函数负责，返回损失、预测类别和真实标签。
        criterion = nn.CrossEntropyLoss()
        test_loss, _test_acc, preds, labels = evaluate_with_predictions(
            model, test_loader, criterion, device
        )

        # 保持既有指标口径：accuracy 及宏平均 precision、recall、F1。
        metrics = compute_metrics(preds, labels)
        logger.info("=" * 55)
        logger.info("%s Test Results:", config.name.upper())
        logger.info("  Accuracy:  %.4f", metrics["accuracy"])
        logger.info("  Precision: %.4f", metrics["precision"])
        logger.info("  Recall:    %.4f", metrics["recall"])
        logger.info("  F1-Score:  %.4f", metrics["f1"])
        logger.info("  Test Loss: %.4f", test_loss)
        logger.info("=" * 55)

        # 矩阵覆盖所有模型类别（含未出现的类别），图片坐标轴显示对应的原始标签。
        cm = confusion_matrix(labels, preds, labels=range(mapping.num_classes))
        metric_path = metrics_dir()
        metric_path.mkdir(parents=True, exist_ok=True)
        cm_path = Path(add_exclusion_suffix(metric_path / config.cm_array_name, args.exclude_labels))
        np.save(cm_path, cm)
        logger.info("Confusion matrix saved to %s", cm_path)

        cm_image_path = Path(args.cm_image_path)
        cm_image_path.parent.mkdir(parents=True, exist_ok=True)
        save_confusion_matrix_image(cm, cm_image_path, class_labels=mapping.original_labels)
        logger.info("Confusion matrix image saved to %s", cm_image_path)
    finally:
        # 正常结束或任一步骤失败时，都关闭数据集持有的 H5 句柄。
        dataset.close()


if __name__ == "__main__":
    main()
